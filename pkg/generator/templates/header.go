package templates

// HeaderData is the data HeaderTemplate is executed with.
type HeaderData struct {
	// Package is the name of the generated package.
	Package string
	// Context reports whether the generated code uses the context package.
	Context bool
	// SOAP reports whether the generated code uses the gowsdl soap package.
	SOAP bool
}

// HeaderTemplate is the template for generating file headers. It is executed
// with a HeaderData value.
const HeaderTemplate = `
// Code ` + `generated by gowsdl DO NOT EDIT.

package {{.Package}}

import (
	{{- if .Context}}
	"context"
	{{- end}}
	"encoding/xml"
	"time"
	{{- if .SOAP}}

	"github.com/kastrul/gowsdl/soap"
	{{- end}}
)

// against "unused imports"
var _ time.Time
var _ xml.Name

type AnyType struct {
	InnerXML string ` + "`" + `xml:",innerxml"` + "`" + `
}

type AnyURI string

type NCName string

`
